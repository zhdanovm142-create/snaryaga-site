export type ProductTagKind = "default" | "new" | "hit";

export interface ProductSpec {
  /** Короткая метка, напр. "Объём" */
  label: string;
  /** Значение, напр. "20 л" */
  value: string;
}

export interface ProductFeature {
  /** Иконка-эмодзи */
  icon: string;
  title: string;
  desc: string;
}

export interface Product {
  id: string;
  /** Короткая линейка (англ. ключ), напр. "Assault Pack" / "IR Suit" */
  category: string;
  /** Человекочитаемое название, напр. "Рюкзак «Тень-20»" */
  name: string;
  /** Объём / характеристика для бейджа, напр. "20L" */
  capacity?: string;
  tag?: string;
  tagKind?: ProductTagKind;
  description: string;
  /** Развёрнутое описание для модалки деталей */
  longDescription?: string;
  price: string;
  /** Старая цена (для отображения зачёркнутой) — опционально */
  oldPrice?: string;
  images: {
    main: string;
    hover: string;
  };
  alt: {
    main: string;
    hover: string;
  };
  /** Короткие спецификации для модалки */
  specs?: ProductSpec[];
  /** Ключевые фичи для модалки */
  features?: ProductFeature[];
  /** Краткое описание зоны покрытия для матрицы подбора, напр. "Капюшон, куртка, брюки" */
  coverage?: string;
  /** Число экранирующих слоёв (1 или 2) — для матрицы подбора */
  layers?: 1 | 2;
  /** Двусторонний (реверс) — для матрицы подбора */
  reversible?: boolean;
  /** Короткое применение — для матрицы подбора («Короткие выходы», «Флагман» и т.д.) */
  useCase?: string;
  /** Признак «рекомендуем» для подсветки в матрице подбора */
  recommended?: boolean;
  /** Остаток на складе для urgency-бейджа (шт.). null = нет данных. */
  stock?: number;
  /** ID товаров, которые часто берут вместе (для cross-sell блока) */
  boughtTogether?: string[];
  /** Срок изготовления */
  leadTime?: string;
}

